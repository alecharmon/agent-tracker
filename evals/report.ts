// Rescore saved run records and write evals/report.md (tables) plus one events dump per run.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { CRITERIA, type Criterion, type Result, type RunRecord, score } from "./score.ts";

const NOTES = "<!-- notes: everything below this line is kept when the report is regenerated -->";
const cell = (r: Result) => (r.pass === null ? "·" : r.pass ? "pass" : "**FAIL**");
const tally = (rs: Result[]) => `${rs.filter((r) => r.pass).length}/${rs.filter((r) => r.pass !== null).length}`;

function dump(r: RunRecord, s: Record<Criterion, Result>) {
  const L = [`# ${r.label} · ${r.harness} · ${r.scenario}`, "", `skill \`${r.skill}\`, started ${r.started}`, ""];
  L.push("## Score", "", "| criterion | result | reason |", "|---|---|---|");
  for (const [c, name] of CRITERIA) L.push(`| ${name} | ${cell(s[c])} | ${s[c].reason.replace(/\|/g, "\\|")} |`);
  L.push("", "## Phases", "", ...r.phases.map((p) => `- **${p.name}** ${p.started} → ${p.ended}, exit ${p.exit}${p.timedOut ? " (timed out)" : ""}, session \`${p.session ?? "?"}\``));
  if (r.notes.length) L.push("", ...r.notes.map((n) => `- note: ${n}`));
  L.push("", "## Captain", "", ...r.captain.map((c) => `- ${c.at} answered \`${c.item}\` (${c.kind}): \`${JSON.stringify(c.body)}\` → expect \`${JSON.stringify(c.expect)}\``),
    ...r.messages.map((m) => `- ${m.at} message: ${m.text}`), ...r.stages.map((x) => `- ${x.at} stage: ${x.stage}`));
  for (const repo of r.repos)
    L.push("", `## Repo ${repo.name}`, "", `- deploys: ${repo.deploys.map((d) => `${d.target} ${d.ts} ${d.sha}`).join("; ") || "none"}`,
      `- tests on main: ${repo.testsPassOnMain}`, ...repo.commits.map((c) => `- ${c.ts} \`${c.sha.slice(0, 7)}\` ${c.subject} (${c.files.join(", ")})`));
  for (const d of r.items) {
    const who = new Map(d.sessions.map((x) => [x.id, `${x.harness}${x.model ? ` (${x.model})` : ""}`]));
    L.push("", `## Task \`${d.item.id}\`: ${d.item.title}`, "", `state ${d.item.state}, repo ${d.item.repo ?? "–"}, parent ${d.item.parent_id ?? "–"}`);
    if (d.item.ask) L.push("", "```json", JSON.stringify(d.item.ask, null, 1), "```");
    L.push("", "| ts | verb | by | text |", "|---|---|---|---|");
    for (const e of [...d.events].sort((a, b) => a.ts.localeCompare(b.ts)))
      L.push(`| ${e.ts.slice(11, 19)} | ${e.verb} | ${e.session_id ? who.get(e.session_id) ?? e.session_id : "captain"} | ${e.text.replace(/\|/g, "\\|").replace(/\n/g, " ")} |`);
  }
  return L.join("\n") + "\n";
}

export function writeReport(resultsDir: string, out: string) {
  const labels = existsSync(resultsDir) ? readdirSync(resultsDir).filter((l) => !l.startsWith(".")).sort() : [];
  const runs = labels.map((l) => ({
    label: l,
    recs: readdirSync(join(resultsDir, l)).filter((f) => f.endsWith(".json")).sort()
      .map((f) => JSON.parse(readFileSync(join(resultsDir, l, f), "utf8")) as RunRecord),
  }));
  const L = ["# Skill eval report", "", "Generated by `npm run evals` (rescore with `npm run evals -- --report`). " +
    "pass / **FAIL** / · (not in this scenario). Each run links to its tracker events.", ""];
  const harnesses = [...new Set(runs.flatMap((r) => r.recs.map((x) => x.harness)))];
  L.push("## Before / after (criteria passed / applicable, all scenarios)", "", `| iteration | skill | ${harnesses.join(" | ")} | total |`, `|---|---|${harnesses.map(() => "---|").join("")}---|`);
  for (const { label, recs } of runs) {
    const scored = recs.map((r) => ({ r, s: score(r) }));
    const by = (h?: string) => tally(scored.filter((x) => !h || x.r.harness === h).flatMap((x) => Object.values(x.s)));
    L.push(`| ${label} | \`${recs[0]?.skill ?? "?"}\` | ${harnesses.map((h) => (recs.some((r) => r.harness === h) ? by(h) : "–")).join(" | ")} | ${by()} |`);
  }
  for (const { label, recs } of [...runs].reverse()) {
    L.push("", `## ${label}`, "", `| run | ${CRITERIA.map(([c]) => c).join(" | ")} | score |`, `|---|${CRITERIA.map(() => "---|").join("")}---|`);
    const fails: string[] = [];
    for (const r of recs) {
      const s = score(r);
      const f = join(resultsDir, label, `${r.id}.md`);
      writeFileSync(f, dump(r, s));
      L.push(`| [${r.harness} · ${r.scenario}](${relative(dirname(out), f)}) | ${CRITERIA.map(([c]) => cell(s[c])).join(" | ")} | ${tally(Object.values(s))} |`);
      for (const [c] of CRITERIA) if (s[c].pass === false) fails.push(`- **${r.harness} · ${r.scenario}** ${c}: ${s[c].reason}`);
    }
    if (fails.length) L.push("", "Failures:", "", ...fails);
  }
  L.push("", "Criteria: " + CRITERIA.map(([c, n]) => `**${c}** ${n}`).join("; ") + ".");
  const prev = existsSync(out) ? readFileSync(out, "utf8") : "";
  const notes = prev.includes(NOTES) ? prev.slice(prev.indexOf(NOTES) + NOTES.length) : "\n";
  writeFileSync(out, L.join("\n") + "\n\n" + NOTES + notes);
}
